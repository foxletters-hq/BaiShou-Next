#!/usr/bin/env node
/**
 * 从 models.dev/api.json 同步带 effort 档位的思考目录，生成本地快照。
 *
 * 更新供应商映射：scripts/provider-modelsdev.manifest.json → pnpm sync
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = join(root, 'scripts/provider-modelsdev.manifest.json')
const snapshotPath = join(root, 'packages/shared/src/data/reasoning-models.snapshot.generated.ts')
const stampPath = join(root, 'packages/shared/src/data/.reasoning-models-sync-stamp.json')

const MODELS_DEV_API = 'https://models.dev/api.json'
const checkOnly = process.argv.includes('--check')
const force = process.argv.includes('--force')

function md5(text) {
  return createHash('md5').update(text).digest('hex')
}

function readManifest() {
  return JSON.parse(readFileSync(manifestPath, 'utf8'))
}

function buildProviderIdMap(manifest) {
  const map = {}
  for (const entry of manifest.providers || []) {
    for (const devId of entry.modelsDevIds || []) {
      map[devId] = entry.id
    }
  }
  return map
}

function asRecord(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null
  return value
}

function collectEffortRecord(model) {
  const rec = asRecord(model)
  if (!rec || !Array.isArray(rec.reasoning_options)) return null
  for (const item of rec.reasoning_options) {
    if (item?.type !== 'effort' || !Array.isArray(item.values)) continue
    const values = [
      ...new Set(item.values.filter((value) => typeof value === 'string' && value.trim()))
    ]
    if (values.length === 0) continue
    return { values }
  }
  return null
}

function extractPayload(api, providerIdMap) {
  const payload = {
    syncedAt: new Date().toISOString(),
    source: MODELS_DEV_API,
    byProvider: {},
    byModelId: {}
  }

  for (const [devProviderId, localProviderId] of Object.entries(providerIdMap)) {
    const models = asRecord(asRecord(api?.[devProviderId])?.models)
    if (!models) continue
    for (const [modelId, model] of Object.entries(models)) {
      const record = collectEffortRecord(model)
      if (!record) continue
      const parts = String(modelId).split('/')
      const base = (parts[parts.length - 1] || '').toLowerCase()
      if (!base) continue
      if (!payload.byProvider[localProviderId]) payload.byProvider[localProviderId] = {}
      payload.byProvider[localProviderId][base] = record
      payload.byModelId[base] = record
    }
  }
  return payload
}

function buildSnapshotTs(payload) {
  return `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/sync-reasoning-models.mjs — do not edit by hand.
 * Source: https://models.dev/api.json + scripts/provider-modelsdev.manifest.json
 */
export const REASONING_MODELS_SNAPSHOT = ${JSON.stringify(payload, null, 2)} as const
`
}

async function syncReasoningModels() {
  const manifest = readManifest()
  const manifestHash = md5(readFileSync(manifestPath, 'utf8'))
  const stamp = existsSync(stampPath) ? JSON.parse(readFileSync(stampPath, 'utf8')) : null

  if (!force && stamp?.manifestMd5 === manifestHash && existsSync(snapshotPath)) {
    console.log('[sync-reasoning-models] Up to date (manifest unchanged).')
    return
  }

  const response = await fetch(MODELS_DEV_API, { signal: AbortSignal.timeout(60_000) })
  if (!response.ok) {
    throw new Error(`models.dev returned HTTP ${response.status}`)
  }
  const api = await response.json()
  const payload = extractPayload(api, buildProviderIdMap(manifest))
  const uniqueModels = Object.keys(payload.byModelId).length

  mkdirSync(dirname(snapshotPath), { recursive: true })
  writeFileSync(snapshotPath, buildSnapshotTs(payload), 'utf8')
  writeFileSync(
    stampPath,
    `${JSON.stringify(
      {
        manifestMd5: manifestHash,
        syncedAt: payload.syncedAt,
        uniqueEffortModels: uniqueModels
      },
      null,
      2
    )}\n`,
    'utf8'
  )

  console.log(`[sync-reasoning-models] Wrote snapshot: ${uniqueModels} models with effort options.`)
}

function checkReasoningModels() {
  const manifestHash = md5(readFileSync(manifestPath, 'utf8'))
  const stamp = existsSync(stampPath) ? JSON.parse(readFileSync(stampPath, 'utf8')) : null

  if (!stamp || stamp.manifestMd5 !== manifestHash) {
    console.error('[sync-reasoning-models] Snapshot out of date. Run: pnpm sync')
    process.exit(1)
  }
  if (!existsSync(snapshotPath)) {
    console.error('[sync-reasoning-models] Missing generated snapshot. Run: pnpm sync')
    process.exit(1)
  }
  console.log('[sync-reasoning-models] OK')
}

if (checkOnly) {
  checkReasoningModels()
} else {
  await syncReasoningModels()
}
